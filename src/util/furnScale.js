// 职责：家具「模型原始尺寸 → 世界尺寸」的换算常量。全项目唯一真相源，游戏端与编辑器都从这里取。
//
// 为什么需要：商店那 140 件 Kenney Furniture Kit（CC0）是按「1 单位 ≈ 0.4 m」建模的，
//   直接摆出来只有真实家具的三分之一左右（双人床 1.1 m 长、浴缸 1.1 m 长），看着像玩具模型。
//   统一基座放大 3 倍后接近真实家具尺度。
//
// ⚠⚠ 两条铁律（改之前先读）：
//   1. **它只影响渲染缩放，不写进任何持久化数据**。服务端 build 记录里的 scale 是「相对这个基座」的
//      倍率（1 = 基座大小），所以已经摆好的家具改这个常量会**立刻跟着变大，不需要迁移任何数据**。
//      反过来：绝不能把它乘进 rec.scale 再发给服务端（那等于每次编辑都叠加一次，越调越大）。
//   2. **若以后把缩放烘进 GLB**（改 glTF 根节点 scale = [3,3,3]），必须把这里改回 1，
//      否则两处叠加成 9 倍。二选一，不要两边都做。
export const FURN_BASE_SCALE = 3;

// 只作用于商店家具（商品 id 以 furn_ 开头）。
// 组合家具（编辑器自己搭的 combo）、建筑、道具等一律返回 1，不受影响。
export function baseScaleOf(itemId) {
  return /^furn_/.test(String(itemId || '')) ? FURN_BASE_SCALE : 1;
}
