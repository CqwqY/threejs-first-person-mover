/**
 * 重绘字母/数字键位图块（a-z、d0-d9）。
 *
 * 为什么需要：
 *   Kenney 的图集没有命名文件，键位图块全靠 tools/extract-input-prompts.mjs 里手写的 (row,col) 认。
 *   实测发现**字母区整体错位**：
 *     · a.png 画的是「↑ 箭头」、g.png 画的是「F」、b.png 画的是「U/V」
 *     · 而 q/w/e/r… 行（第 2 行）、数字行、SHIFT / ESC / F5 都是对的
 *   → 第 3 行(A S D F G H J K L)、第 4 行(Z X C V B N M) 的坐标不可靠，且无法反推。
 *   原图集不在仓库，所以这里用 5x7 点阵字体**直接画**，风格对齐 Kenney（浅键帽 + 深描边 + 底部厚边）。
 *
 * 只重绘单字母/数字（保证这一区风格统一）；单词键（SHIFT/ESC/F5/SPACE…）实测正确，保持原样。
 *
 * 用法：node tools/redraw-key-tiles.mjs          # 重绘全部字母+数字
 *       node tools/redraw-key-tiles.mjs g b      # 只重绘指定键
 */
