function inRoundRect(x, y, x0, y0, x1, y1, r) {
  if (x < x0 || x > x1 || y < y0 || y > y1) return false;
  const cx = Math.min(Math.max(x, x0 + r), x1 - r);
  const cy = Math.min(Math.max(y, y0 + r), y1 - r);
  const dx = x - cx, dy = y - cy;
  return dx * dx + dy * dy <= r * r + 0.35;
}

function drawKey(ch) {
  const rgba = Buffer.alloc(W * H * 4);
  const put = (x, y, c) => {
    const i = (y * W + x) * 4;
    rgba[i] = c[0]; rgba[i + 1] = c[1]; rgba[i + 2] = c[2]; rgba[i + 3] = c[3];
  };
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      if (!inRoundRect(x, y, 1, 0, 14, 15, 2)) { put(x, y, NONE); continue; }   // 描边外形
      if (!inRoundRect(x, y, 2, 1, 13, 11, 2)) { put(x, y, STROKE); continue; } // 外描边
      if (y >= 13) { put(x, y, SIDE); continue; }                              // 底部厚边
      put(x, y, FACE);                                                         // 键帽面
    }
  }
  // 字母居中：5 宽 7 高 → x 从 5 起、y 从 3 起
  const g = GLYPHS[ch];
  if (g) {
    for (let r = 0; r < g.length; r++) {
      for (let c = 0; c < g[r].length; c++) {
        if (g[r][c] !== '1') continue;
        put(5 + c, 3 + r, STROKE);
      }
    }
  }
  return encodePNG(rgba, W, H);
}

const args = process.argv.slice(2);
const targets = args.length
  ? args.map((a) => (a.startsWith('d') && a.length === 2 ? a.slice(1) : a).toUpperCase())
  : [...'ABCDEFGHIJKLMNOPQRSTUVWXYZ', ...'0123456789'];

for (const ch of targets) {
  const name = /[0-9]/.test(ch) ? 'd' + ch : ch.toLowerCase();
  if (!GLYPHS[ch]) { console.log('skip（无字形）', name); continue; }
  writeFileSync(`${OUT_DIR}/${name}.png`, drawKey(ch));
  console.log('written', `${OUT_DIR}/${name}.png`, `<= "${ch}"`);
}
